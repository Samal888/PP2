#1: 1 to 5
i = 1
while i <= 5:
    print(i)
    i += 1

#2: small hello
j = 0
while j < 3:
    print("hello", j)
    j += 1

#3: countdown
k = 5
while k > 0:
    print(k)
    k -= 1

#4: loop counter
n = 1
while n <= 3:
    print(n)
    n += 1

#5: even numbers
x = 2
while x <= 10:
    print(x)
    x += 2
